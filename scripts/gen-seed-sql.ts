// Generates supabase/seed.sql directly from src/lib/seed-data.ts so the two
// can never drift apart. Run with `npm run gen:seed`.
//
// This script is TypeScript and is executed with `vite-node` (already
// available transitively via vitest) rather than a plain `node`, so it can
// import seed-data.ts without a separate build step.

import { writeFileSync } from "fs";
import path from "path";
import { COMMUTE, SAMPLE_LISTINGS, LANDMARK_LABELS } from "../src/lib/seed-data";

function sqlString(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function sqlBool(b: boolean | null): string {
  if (b === null) return "null";
  return b ? "true" : "false";
}

function sqlNum(n: number | null): string {
  return n === null ? "null" : String(n);
}

const lines: string[] = [];
lines.push("-- Generated by scripts/gen-seed-sql.ts from src/lib/seed-data.ts.");
lines.push("-- Do not edit by hand; run `npm run gen:seed` instead.");
lines.push("");

lines.push("-- Commute table: approximate peak-hour minutes, 12 areas x 8 landmarks.");
lines.push("insert into commute (area, landmark, minutes) values");
lines.push(
  COMMUTE.map(
    (c, i) =>
      `  (${sqlString(c.area)}, ${sqlString(c.landmark)}, ${c.minutes})${
        i === COMMUTE.length - 1 ? ";" : ","
      }`
  ).join("\n")
);
lines.push("");

lines.push("-- Sample listings (shared across all groups; group_id is null).");
lines.push(
  "insert into listings (id, group_id, title, area, rent, floor, lift, parking, pets, bathrooms, furnished, balcony, gym, near_metro, newer, url, is_sample, status) values"
);
lines.push(
  SAMPLE_LISTINGS.map((l, i) => {
    const row = [
      l.id,
      "null",
      sqlString(l.title),
      sqlString(l.area),
      l.rent,
      l.floor,
      sqlBool(l.lift),
      sqlBool(l.parking),
      sqlBool(l.pets),
      sqlNum(l.bathrooms),
      sqlBool(l.furnished),
      sqlBool(l.balcony),
      sqlBool(l.gym),
      sqlBool(l.near_metro),
      sqlBool(l.newer),
      l.url ? sqlString(l.url) : "null",
      "true",
      sqlString(l.status),
    ].join(", ");
    return `  (${row})${i === SAMPLE_LISTINGS.length - 1 ? ";" : ","}`;
  }).join("\n")
);
lines.push("");
lines.push(
  "-- Keep the id sequence ahead of the highest hand-assigned sample id, so\n" +
    "-- organiser-added listings (which omit id) never collide with samples."
);
lines.push(
  `select setval(pg_get_serial_sequence('listings', 'id'), ${Math.max(
    ...SAMPLE_LISTINGS.map((l) => l.id)
  )}, true);`
);
lines.push("");

const out = lines.join("\n") + "\n";
const outPath = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${SAMPLE_LISTINGS.length} listings, ${COMMUTE.length} commute rows).`);
console.log(`Landmarks: ${Object.keys(LANDMARK_LABELS).join(", ")}`);
